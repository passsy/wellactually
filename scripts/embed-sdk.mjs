// Writes the SDK's source into the core as strings.
//
// The bundler has to hand the SDK to esbuild wherever it runs. A browser has
// no filesystem to read it from, so the source travels inside the code. The
// output is a build artifact and not in Git: npm runs this before typecheck,
// test, build and package, and vitest runs it before any test.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "packages/detector-sdk/src");
const sources = Object.fromEntries(
  fs
    .readdirSync(dir)
    // `*.node.ts` runs on an author's machine, outside the isolate, and is not part of what gets bundled.
    .filter((name) => name.endsWith(".ts") && !name.endsWith(".node.ts"))
    .sort()
    .map((name) => [name, fs.readFileSync(path.join(dir, name), "utf8")]),
);
const out = `// Generated by scripts/embed-sdk.mjs from packages/detector-sdk/src. Do not edit.
export const SDK_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};
`;
fs.writeFileSync(path.join(root, "packages/core/src/build/sdk-source.generated.ts"), out);
